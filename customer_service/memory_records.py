from urllib.parse import urlsplit

MEMORY_TYPES = ('user', 'feedback', 'project', 'reference')
TYPE_LABELS = {'user': '用户偏好', 'feedback': '长期反馈', 'project': '项目背景', 'reference': '资料线索'}
RECORD_KEY_PATTERN = re.compile(r'record_[0-9a-f]{24}')
