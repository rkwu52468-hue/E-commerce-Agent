def normalized_body(body):
    return ' '.join(body.split())


def record_key(kind, body):
    digest = hashlib.sha256((kind + '\n' + normalized_body(body)).encode('utf-8')).hexdigest()[:24]
    return 'record_' + digest


def candidate_key(candidate):
    return candidate['key'] if 'key' in candidate else record_key(candidate['type'], candidate['evidence'])


def record_description(kind, body):
    return TYPE_LABELS[kind] + '（客户自述）：' + ' '.join(body.split())[:80]


def is_memory_key(key):
    return isinstance(key, str) and (key in ('reply_language', 'reply_detail')
                                    or RECORD_KEY_PATTERN.fullmatch(key) is not None)


def complete_sentences(query):
    # Keep commas/conditions together; dots inside URLs are not sentence breaks.
    parts = re.split(r'(?<=[。！？!?；;])|\n+|(?<=\.)\s+', query)
    return {query.strip(), *(part.strip() for part in parts if part.strip())}


def resolve_source_evidence(query, evidence):
    """Return a complete original source unit, never a model-rewritten body.

    Only exterior whitespace and one final full stop may differ. URL and question
    punctuation remains exact because changing it could change the reference or
    intent. Commas, conditions and negations are never stripped.
    """
    if not isinstance(query, str) or not isinstance(evidence, str):
        return None
    proposed = evidence.strip()
    if not proposed:
        return None
    units = complete_sentences(query)
    if proposed in units and proposed in query:
        return proposed
    if re.search(r'https?://', proposed) or re.search(r'https?://', query):
        return None
    def without_full_stop(text):
        return text[:-1] if text.endswith(('。', '.')) else text
    matches = {unit for unit in units if unit and without_full_stop(unit) == without_full_stop(proposed)}
    return next(iter(matches)) if len(matches) == 1 else None


def note_candidate(diagnostics, kind, scope, reason, evidence_adjusted=False):
    if diagnostics is not None:
        diagnostics.append({'kind': kind, 'scope': scope, 'reason': reason,
                            'evidence_adjusted': bool(evidence_adjusted)})


def _reference_is_safe(text):
    urls = re.findall(r'https?://[^\s<>“”"\'，。；]+', text)
    if not urls:
        return False
    for raw in urls:
        try:
            url = urlsplit(raw.rstrip('.,;!?)）'))
            _ = url.port  # Validate an explicitly supplied port without resolving or fetching.
            if (url.scheme != 'https' or not url.hostname or url.username or url.password
                    or url.query or url.fragment or len(raw) > 512
                    or re.fullmatch(r'[A-Za-z0-9.-]+', url.hostname) is None):
                return False
        except ValueError:
            return False
    return True


def admit_record_candidates(query, candidates, diagnostics=None):
    if (not isinstance(query, str) or not isinstance(candidates, list) or len(candidates) > MAX_CANDIDATES
            or (diagnostics is not None and not isinstance(diagnostics, list))):
        raise ValueError('Invalid record candidates')
    folded_query = query.casefold()
    quoted_context = re.sub(r'https?://[^\s<>]+', '', folded_query)
    veto = (any(word in folded_query for word in (*NO_STORE, *FORBIDDEN))
            or any(word in quoted_context for word in QUOTED)
            or re.search(r'(?i)\b(?:[AB]\d{4,}|P\d{3,})\b', query) is not None
            or re.search(r'(?<!\d)1[3-9]\d{9}(?!\d)', query) is not None
            or re.search(r'(?i)\bsk-[a-z0-9]{16,}', query) is not None)
    accepted, seen = [], set()
    for item in candidates:
        if (not isinstance(item, dict) or set(item) != {'type', 'scope', 'evidence'}
                or not all(isinstance(value, str) for value in item.values())
                or item['type'] not in MEMORY_TYPES or item['scope'] not in ('persistent', 'current_task')
                or not 1 <= len(item['evidence']) <= MAX_EVIDENCE_CHARS):
            raise ValueError('Invalid record candidate')
        kind, scope = item['type'], item['scope']
        evidence = resolve_source_evidence(query, item['evidence'])
        adjusted = evidence is not None and evidence != item['evidence']
        reason = None
        if veto:
            reason = 'blocked_source'
        elif scope != 'persistent':
            reason = 'nonpersistent_scope'
        elif evidence is None or len(evidence) > MAX_EVIDENCE_CHARS:
            reason = 'evidence_not_source_sentence'
        elif any(word in evidence.casefold() for word in TEMPORARY):
            reason = 'temporary_scope'
        elif any((ord(c) < 32 and c not in '\n\t') or ord(c) == 127 for c in evidence):
            reason = 'invalid_source_characters'
        if reason:
            note_candidate(diagnostics, kind, scope, reason, adjusted)
            continue
        folded = evidence.casefold()
        durable = any(word in folded for word in DURABLE)
        style = any(word in folded for word in STYLE)
        if kind == 'project':
            suitable = (any(folded.startswith(prefix) for prefix in SELF_PROJECT)
                        and not any(word in folded for word in ('订单', '物流', '政策', '退款', '售后', '权限', '配置', '密钥')))
        elif kind == 'reference':
            suitable = durable and _reference_is_safe(evidence)
        elif kind == 'feedback':
            suitable = durable and style
        else:
            suitable = durable and (style or any(word in folded for word in ('我喜欢', '我更喜欢', '我偏好', '我长期偏好', '我习惯', '我的偏好', 'i prefer', 'my preference')))
        if kind != 'reference' and re.search(r'https?://', evidence):
            suitable = False
        if re.search(r'\d+(?:\.\d+)?\s*(?:元|天内|小时内|日内)', evidence):
            suitable = False
        if not suitable:
            reason = 'no_long_term_intent' if not durable and kind != 'project' else 'unsupported_record_context'
            note_candidate(diagnostics, kind, scope, reason, adjusted)
            continue
        key = record_key(kind, evidence)
        if key in seen:
            raise ValueError('Duplicate record candidate')
        seen.add(key)
        accepted.append({**item, 'evidence': evidence})
        note_candidate(diagnostics, kind, scope, 'accepted', adjusted)
    return accepted
